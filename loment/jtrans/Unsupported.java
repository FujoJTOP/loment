/*
 * Unsupported.java —— **反例语料**：这份 Java 里有本子集外的写法。
 *
 * 存在的唯一理由是让"不静默丢"这条纪律**可被判据钉住**（`docs/167`）。子集外的写法
 * 被悄悄跳过的话，`lomt_from --impl` 发出来的就是一份**少算了一步却照样能编过**的
 * 单元 —— 比拒绝坏得多。
 *
 * 这里放的是 Java **特有**的那一处：`>>>` 是**逻辑**右移，而本语言的 `>>` 是
 * **算术**的（实测 `-8 >> 1 == -4`）。所以 `>>>` 不能直接映过去。
 *
 * **它是个"能表达出来的差"**：`a >>> n` 写成 `(a as u32) >> n` 就行。现在**不收** ——
 * 没有语料逼它，别急着补（补了就要为它写判据，而判据要有对照组）。
 */
public class Unsupported {
    public static int shift(int a) {
        return a >>> 1;
    }
}
