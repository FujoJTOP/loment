"""intdiv.py —— **不同意集**：`//` 与 `%` 在负号上两边不一样，而**照 Loment 的来**。

    Python  `-7 // 2 == -4`   `-7 % 2 == 1`      （**向下取整**）
    Loment  `-7 /  2 == -3`   `-7 %  2 == -1`     （**向零截断**，实测）

## 这一份为什么留在仓里（而不是"改成两边一致就算了"）

第一版（`docs/187` 初稿）在这里发了一对辅助函数 `__py_mod` / `__py_floordiv`，
**去保住 CPython 的向下取整**。按 `docs/188` §0 那是**方向反了**：

> 表层语法只决定拼法与形状，不决定语义。
> `//` 是"**整除**"的拼法，而本语言的整除是向零截断的。

所以现在 `a // b` 直接映 `a / b`，`a % b` 直接映 `a % b`。这一份语料的作用
**整个变了**：它不再是"证明我们保住了 Python 的语义"，而是**钉住我们没有去保住**。

判据因此也不是"== CPython"（那在这儿是**错的**），而是：

* 翻译出来的 Loment 跑出 **62**（本语言算的）；
* **且 62 ≠ 56** —— 56 是 CPython 给的那个数。两个数**必须不同**，否则这一份
  语料没踩在缝上，"我们没迁就 Python"这句话就没被测到。

四个符号组合都走一遍：只试 `-7 // 2` 的话，`%` 那两侧的符号各会漏掉一个组合。
"""

NEG = -7


def fdiv(a: int, b: int) -> int:
    return a // b


def fmod(a: int, b: int) -> int:
    return a % b


def main() -> int:
    q1 = fdiv(NEG, 2)
    q2 = fdiv(7, -2)
    m1 = fmod(NEG, 2)
    m2 = fmod(7, -2)
    # 商都是负的，各挪 20 转正；余数在两侧各有一个符号
    return (q1 + q2 + 20) * 3 + (m1 + m2 + 20)
