"""blockscope.py —— **同意集**：块里声明、块外用，两边**本来就一致**。

    if c:
        x = 10
    else:
        x = 20
    return x

## 这一份的来历：它推翻了写它的人的一个断言（2026-09-18）

`docs/187` 初稿把"**Python 是函数级作用域、Loment 的 `let` 是块级**"列成三处语义差之一，
于是把声明**上提到函数头**去迁就。`docs/188` §0.1 接着把它写成"做反了"的一处。

**两处都错了 —— 那个差根本不存在。** 探出来的（不是推出来的）：

    fn f(c: bool) -> i32 {
        if c { let x: i32 = 10; } else { x = 20; }
        return x;
    }

    * `lomentc.check`：**不报错** —— 块里 `let` 的名，块外看得见；
    * 编出来跑 `f(false)`：给 **20** —— 只有一条分支声明、另一条只赋值，值也对。

⇒ **Loment 的 `let` 在 `if` / `while` 块里就是能漏到块外的**（至少这两个形状如此），
与 Python 的函数级作用域**在这一处一致**。所以：

* 第一版那个"上提"不是"方向反了"，是**多余**；
* 现在这一门不迁就、也不上提 —— 就地 `let` 的结果两边本来就一样。

**所以这一份是"同意集"的语料**，不是"拒收集"：拿 CPython 当对照组，两边都给 120。
（把断言写错的那个代价：一条本不存在的"语义差"被写进文档，还换了一次实现。）

期望：`pick(1)*10 + pick(0) = 10*10 + 20 = **120**`。
"""


def pick(c: int) -> int:
    if c:
        x = 10
    else:
        x = 20
    return x


def main() -> int:
    return pick(1) * 10 + pick(0)
