"""floordiv.py —— **专挑 `//` 与 `%` 的符号**（`docs/187` §为什么）。

这一门里最容易翻错、而且**翻错了照样编得过**的一处：

    Python  `-7 // 2 == -4`   `-7 % 2 == 1`      （**向下取整**）
    Loment  `-7 /  2 == -3`   `-7 %  2 == -1`     （**向零截断**，实测）

所以直译 `a // b` -> `a / b` 是**错的**（只在同号时对）。这一门用一对辅助函数把它补上：

    __py_mod(a, b)      = ((a % b) + b) % b
    __py_floordiv(a, b) = (a - __py_mod(a, b)) / b

四个符号组合都在这份语料里走一遍 —— 只试 `-7 // 2` 的话，那两条恒等式里的
`+ b` 与随后那次 `% b` 各自会漏掉一个符号组合。

`main()` 期望 **56**，而"按 Loment 原生语义直译"会得到 **62** —— 判据里两条都比，
为的是证明这份语料**真的踩在那条缝上**，不是摆样子。
"""
NEG = -7


def fdiv(a: int, b: int) -> int:
    return a // b


def fmod(a: int, b: int) -> int:
    return a % b


def main() -> int:
    q1 = fdiv(NEG, 2)
    q2 = fdiv(7, 0 - 2)
    m1 = fmod(NEG, 2)
    m2 = fmod(7, 0 - 2)
    # 商都是负的，各挪 20 转正；余数在两侧各有一个符号
    return (q1 + q2 + 20) * 3 + (m1 + m2 + 20)
