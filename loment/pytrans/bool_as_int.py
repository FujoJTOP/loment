"""bool_as_int.py —— **拒收集**：Python 的 `bool` 是 `int` 的子类，而本语言的不是。

    def pick(a: int, b: int) -> int:
        return a and b

Python 里 `1 and 2` 是 **`2`** —— `and` 返回的是**操作数**，不是布尔。而本语言的
`&&` 出 `bool`，**这个意思表达不出来**。

## 为什么不照翻

照翻成 `return (a != 0) && (b != 0);` 的话两边都编得过，**只有数不一样**：
`pick(1, 2)` 在 Python 里给 `2`、在本语言里给 `1`。这正是本仓反复要消灭的形状
（`docs/167`），比拒绝坏得多。

## 判据：**属于哪一张表，决定怎么处置**

`docs/188` §0 定的那条判据 —— **能表达的就转，表达不出来的就报错**：

* `if x:`（x 是 int）→ 能表达成 `x != 0` → **转**（那是"整数当条件"的两种拼法）；
* 这里 → **表达不出来** → **报错**，而且要说清为什么（"Python 的 `and` 返回操作数"）。

**注意报错的是《「前端」还是《Loment 的检查器》**：这一条由**前端**报，因为它只有前端
知道"这个位置在 Python 那边本来是个操作数"。而见 `block_scope.py` —— 那一条是
**Loment 的检查器**报的（前端管不着作用域）。
"""


def pick(a: int, b: int) -> int:
    return a and b


def main() -> int:
    return pick(1, 2)
