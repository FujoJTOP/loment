"""unary_invert.py —— **拒收集**：`~` 在本语言里**没有对应的一元运算符**。

    def flip(a: int) -> int:
        return ~a

## 这一份的来历：一个**能过翻译器、过不了词法器**的洞

翻译器原先把 `ast.Invert` 直接映成 `"~"` 发出去，而 Loment 的一元运算符**只有** `-` 与
`!`（词法器没有 `~` 这个字符）。于是：

    $ pytrans f.py            # 成功，发出 ( ~a )
    $ lomc.LomError: 非法字符 '~'

**产物是一份编不过的源**，而报出来的那个错还带着**生成出来的那个单元**的行号 ——
用户看到的是一句指向别处的诊断。与 `**` / `/` 那两处（同一条纪律）合起来是同一族：
前端放过一个后面必然炸的东西。

## 为什么不照翻（它**本可以**转）

`~v` 的意思在无符号宽度上是确定的："与全 1 异或" —— i32 上是 `v ^ -1`、u8 上是
`v ^ 255`。**但翻译器不做整数宽度跟踪**（`docs/188` §7.1.1）：`a` 是 `i32` 还是 `u8`
在这里无从知道，所以**它替不了你选**。

按 `docs/188` §0 那条判据 —— **能表达的就转，表达不出来的就报错** —— 这里属于
"能表达、但这台翻译器表达不出来"。与 `>>>`（逻辑右移）同一条：**先不收，除非有语料逼它**。
真要它，就按宽度显式写 `a ^ -1`（i32）或 `a ^ 255`（u8）—— 那是作者的选择，不是翻译器的。

## 另一条路也被否掉了

"让它过、报个警告"不行：**静默产出一份编不过的源**比拒绝坏得多（`docs/167` 那条）。
这一门是"全有或全无"——要么发出来的东西能编，要么明确说这条不收。

## 判据

`loment_pytrans_test::test_unary_invert_is_refused_by_the_front_end`——
**前端报错，且说得出为什么**（要提到"宽度"或"按宽度写"），并**钉住另一半**：
`-a` 与 `+a` 照旧收（那两处本语言有一元运算符）。翻译器的 Loment 孪生也跟着拒，
逐字节判据在 `loment_trans_test::test_lomtrans_python_out_of_subset_is_loud` 那一族里。
"""


def flip(a: int) -> int:
    return ~a
