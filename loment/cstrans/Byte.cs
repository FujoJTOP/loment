/*
 * Byte.cs —— **只有一种宽度**的一份 C#：从头到尾都是 `byte`。
 *
 * 它钉的是 `docs/188` §7.1.1 那条边界的**另一半**：
 *
 * > 那条边界是"**混**宽度"才触发的，不是"窄类型"本身。
 *
 * `Sample.cs` 钉的是"同一个程序、两种拼法"（用 `int`，与 Java 的那份逐行同源）。
 * 这一份钉的是另一件事：**一份全 `byte` 的单元能整个翻过去、而且跑得对**。
 *
 * ## 它的**值**就是判据
 *
 * `probe((byte)200)` 里 `200 >= 128` 为真 ⇒ 返回 **200**。若翻译器把 `byte` 映成
 * **有符号**的 `i8`（Java 那个格子），200 到不了这里（`i8` 装不下，当场报错）
 * 或者变成 -56（`-56 >= 128` 为假 ⇒ 返回 0）—— **两种都让数对不上**。
 *
 * ⇒ 所以这一份**同时端到端地证明了 `byte` 是无符号的**。那一格原先只在
 * `potato_from` 的**对象层**验过（`test_csharp_byte_is_unsigned_unlike_java`）；
 * 端到端那一半一直空着，因为混宽度会撞上那条边界 —— 而**不混**就不撞。
 *
 * ## 为什么它**不能**放进 `Sample.cs`
 *
 * 因为 `Sample.cs` 与 `Sample.java` 是**同一个程序的两种拼法**（判据要求两者翻出来的
 * Loment 逐行完全相同），而 `byte` 的符号性**正是这两门唯一不同的一格**：
 * Java 的 `byte` 装不下 200，写不出等价的那一段。把它塞进共享语料会当场把那条判据弄红
 * —— 实测撞到过，这正是它单独一份的原因。
 *
 * **不混宽度是刻意的**：混了就会落进那条边界（响亮地失败），而这一份要证明的是
 * "窄类型本身能过"。
 */
using System;

namespace LomentDemo
{
    public class ByteProbe
    {
        public static byte probe(byte b)
        {
            if (b >= 128)
            {
                return b;
            }
            return 0;
        }
    }
}
